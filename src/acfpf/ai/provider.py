from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Protocol


class AIError(RuntimeError):
    """Base class for AI integration failures."""


class AIProviderNotConfigured(AIError):
    """Raised when no usable LLM provider is configured."""


class AIProviderError(AIError):
    """A safe provider error, suitable for the API and the observable progress stream."""

    def __init__(
        self,
        message: str,
        *,
        code: str = "invalid_response",
        http_status: int | None = None,
        retry_after: float | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.http_status = http_status
        self.retry_after = retry_after

    def as_dict(self) -> dict[str, Any]:
        return {
            "code": self.code,
            "message": str(self),
            "provider_status": self.http_status,
            "retry_after": self.retry_after,
        }


class AIGroundingError(AIError):
    """Raised when an answer violates ACFPF grounding constraints."""


@dataclass(frozen=True)
class ProviderRequest:
    system_prompt: str
    user_prompt: str
    response_schema: dict[str, Any] | None = None
    response_schema_name: str | None = None


class LLMProvider(Protocol):
    name: str
    model: str

    def complete_json(self, request: ProviderRequest) -> dict:
        """Return one JSON object generated by the provider."""
        ...
