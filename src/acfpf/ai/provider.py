from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


class AIError(RuntimeError):
    """Base class for AI integration failures."""


class AIProviderNotConfigured(AIError):
    """Raised when no usable LLM provider is configured."""


class AIProviderError(AIError):
    """Raised when a provider request fails or returns an invalid payload."""


class AIGroundingError(AIError):
    """Raised when an answer violates ACFPF grounding constraints."""


@dataclass(frozen=True)
class ProviderRequest:
    system_prompt: str
    user_prompt: str


class LLMProvider(Protocol):
    name: str
    model: str

    def complete_json(self, request: ProviderRequest) -> dict:
        """Return one JSON object generated by the provider."""
        ...
